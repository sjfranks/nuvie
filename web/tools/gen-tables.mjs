// Generates src/game/u6tables.ts from Nuvie's C++ headers (U6objects.h, U6ActorTypes.h).
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../../', import.meta.url);
const objs = {};
const all = {};
for (const m of readFileSync(new URL('U6objects.h', root), 'latin1').matchAll(/#define\s+(OBJ_(U6|SE|MD)_\w+)\s+(\d+)/g)) {
  all[m[1]] = +m[3];
  if (m[2] === 'U6') objs[m[1]] = +m[3];
}
// The stackable things of Savage Empire and Martian Dreams, as ObjManager::is_stackable lists them.
const om = readFileSync(new URL('ObjManager.cpp', root), 'latin1');
const body = om.slice(om.indexOf('bool ObjManager::is_stackable'));
const section = (tag) => {
  const a = body.indexOf(`game_type==${tag}`) >= 0 ? body.indexOf(`game_type==${tag}`) : body.indexOf(`game_type == ${tag}`);
  const b = body.indexOf('return true;', a);
  return [...body.slice(a, b).matchAll(/case (OBJ_\w+)/g)].map((m) => all[m[1]]).filter((v) => v !== undefined);
};
const stack = { se: section('NUVIE_GAME_SE'), md: section('NUVIE_GAME_MD') };
const mt = { MOVETYPE_U6_NONE: 0, MOVETYPE_U6_LAND: 1, MOVETYPE_U6_WATER_LOW: 2, MOVETYPE_U6_WATER_HIGH: 3, MOVETYPE_U6_AIR_LOW: 4, MOVETYPE_U6_AIR_HIGH: 5, MOVETYPE_U6_ETHEREAL: 6 };
const rows = [];
const typesH = readFileSync(new URL('actors/U6ActorTypes.h', root), 'latin1');
const split = typesH.indexOf('readiable_objects[]');
const LOC = { ACTOR_HEAD: 0, ACTOR_NECK: 1, ACTOR_BODY: 2, ACTOR_ARM: 3, ACTOR_ARM_2: 4, ACTOR_HAND: 5, ACTOR_HAND_2: 6, ACTOR_FOOT: 7 };
const ready = [...typesH.slice(split).matchAll(/\{\s*(OBJ_U6_\w+)\s*,\s*(ACTOR_\w+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\}/g)]
  .filter((m) => m[1] in objs && m[2] in LOC)
  .map((m) => `[${objs[m[1]]}, ${LOC[m[2]]}]`);
for (const m of typesH.slice(0, split).matchAll(/^\s*\{\s*(OBJ_U6_\w+)\s*,([^}]*)\}/gm)) {
  const f = m[2].split(',').map((s) => s.trim());
  const v = (s) => (s in objs ? objs[s] : s in mt ? mt[s] : s === 'true' ? 1 : s === 'false' ? 0 : /^\d+$/.test(s) ? +s : `'${s}'`);
  rows.push(`  [${[objs[m[1]], ...f.map(v)].join(', ')}],`);
}
let out = `// Generated by tools/gen-tables.mjs from Nuvie's U6objects.h and actors/U6ActorTypes.h. Do not edit.\n`;
out += `/* eslint-disable */\nexport const OBJ = {\n${Object.entries(objs).map(([k, v]) => `  ${k.slice(7)}: ${v},`).join('\n')}\n} as const;\n\n`;
out += `/** [obj_n, frames_per_direction, tiles_per_direction, tiles_per_frame, tile_start_offset, dead_obj_n, dead_frame_n, can_laydown, can_sit, tile_type, movetype, twitch_rand, armor_class] */\n`;
out += `export const ACTOR_TYPES: readonly (readonly (number | string)[])[] = [\n${rows.join('\n')}\n];\n`;
out += `\n/** Where each thing is worn or held (U6ActorTypes.h readiable_objects): 0 head, 1 neck, 2 body, 3 one arm, 4 both arms, 5 a hand, 7 feet. */\n`;
out += `export const READY_SLOT = new Map<number, number>([${ready.join(', ')}]);\n`;
out += `\n/** What stacks in Savage Empire and Martian Dreams (ObjManager::is_stackable). */\n`;
out += `export const STACKABLE_SE: readonly number[] = [${stack.se.join(', ')}];\n`;
out += `export const STACKABLE_MD: readonly number[] = [${stack.md.join(', ')}];\n`;
writeFileSync(new URL('../src/game/u6tables.ts', import.meta.url), out);
console.log('stackable se', stack.se.length, 'md', stack.md.length);
console.log(Object.keys(objs).length, 'objects', rows.length, 'actor types');
