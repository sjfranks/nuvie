// Generates src/game/u6combat.ts from Nuvie's data/scripts/u6/actor.lua: the monster table, weapon damage and
// range, armour, and which weapons are thrown or shot.
import { readFileSync, writeFileSync } from 'node:fs';
const lua = readFileSync(new URL('../../data/scripts/u6/actor.lua', import.meta.url), 'latin1');
const ALIGN = { ALIGNMENT_DEFAULT: 0, ALIGNMENT_NEUTRAL: 1, ALIGNMENT_EVIL: 2, ALIGNMENT_GOOD: 3, ALIGNMENT_CHAOTIC: 4 };
const block = (name) => {
  const a = lua.indexOf(name);
  const b = lua.indexOf('\n}', a);
  return lua.slice(a, b);
};
const list = (s) => s.split(',').map((v) => v.trim()).filter(Boolean).map(Number);
const monsters = [];
for (const m of block('actor_tbl = {').matchAll(/\[(\d+)\]\s*=\s*\{([^{}]*?),\s*\{([^}]*)\},\s*\{([^}]*)\},\s*\{([^}]*)\},\s*\{([^}]*)\},\s*(\d+)\}/g)) {
  const f = m[2].split(',').map((v) => v.trim());
  const nums = f.map((v) => (v in ALIGN ? ALIGN[v] : Number(v)));
  monsters.push(`  [${m[1]}, { str: ${nums[0]}, dex: ${nums[1]}, int: ${nums[2]}, hp: ${nums[3]}, dmg: ${nums[4]}, align: ${nums[5]}, ` +
    `blood: ${nums[7]}, fades: ${nums[8]}, halfDmg: ${nums[13]}, poison: ${nums[14]}, useStr: ${nums[15]}, ` +
    `spells: [${list(m[3])}], weapons: [${list(m[4])}], armour: [${list(m[5])}], treasure: [${list(m[6])}], exp: ${m[7]} }],`);
}
const pairs = (name) => [...block(name).matchAll(/\[(\d+)\]\s*=\s*(\d+)/g)].map((m) => `[${m[1]}, ${m[2]}]`).join(', ');
const projectiles = [...block('local projectile_weapon_tbl').matchAll(/\[(\d+)\]\s*=\s*\{(\d+)/g)].map((m) => `[${m[1]}, ${m[2]}]`).join(', ');
let out = `// Generated by tools/gen-combat.mjs from Nuvie's data/scripts/u6/actor.lua. Do not edit.\n/* eslint-disable */\n`;
out += `export interface MonsterType {\n  str: number; dex: number; int: number; hp: number; dmg: number; align: number; blood: number; fades: number;\n  halfDmg: number; poison: number; useStr: number; spells: number[]; weapons: number[]; armour: number[]; treasure: number[]; exp: number;\n}\n`;
out += `/** actor_tbl: each monster's base numbers, by its object number. */\nexport const MONSTERS = new Map<number, MonsterType>([\n${monsters.join('\n')}\n]);\n`;
out += `/** weapon_dmg_tbl */\nexport const WEAPON_DMG = new Map<number, number>([${pairs('weapon_dmg_tbl = {')}]);\n`;
out += `/** armour_tbl */\nexport const ARMOUR = new Map<number, number>([${pairs('armour_tbl =')}]);\n`;
out += `/** g_range_weapon_tbl (every other weapon reaches one square) */\nexport const WEAPON_RANGE = new Map<number, number>([${pairs('g_range_weapon_tbl = {')}]);\n`;
out += `/** projectile_weapon_tbl: weapons thrown or shot, and the tile that flies */\nexport const PROJECTILE = new Map<number, number>([${projectiles}]);\n`;
writeFileSync(new URL('../src/game/u6combat.ts', import.meta.url), out);
console.log(monsters.length, 'monsters');
