// Martian Dreams' English game strings (data/scripts/md/lang/en/game.lua) as a TypeScript table.
import { readFileSync, writeFileSync } from 'node:fs';
const src = readFileSync(new URL('../../data/scripts/md/lang/en/game.lua', import.meta.url), 'latin1');
const out = {};
for (const m of src.matchAll(/^\s*([A-Z0-9_]+)\s*=\s*"((?:[^"\\]|\\.)*)"/gm)) {
  out[m[1]] = m[2].replace(/\\n/g, '\n').replace(/\\"/g, '"').replace(/\\\\/g, '\\');
}
writeFileSync(new URL('../src/game/mdlang.ts', import.meta.url),
  '/** Martian Dreams\' English game strings, from Nuvie\'s data/scripts/md/lang/en/game.lua (generated by tools/gen-mdlang.mjs). */\n' +
  `export const MD_TEXT: Record<string, string> = ${JSON.stringify(out, null, 1)};\n`);
console.log(Object.keys(out).length, 'strings');
